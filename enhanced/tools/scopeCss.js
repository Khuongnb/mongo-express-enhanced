// Library for build-css.js: scopes the designer's stylesheet to `[data-me-enhanced]`.
//
// Upstream injects Bootstrap's CSS from JavaScript (style-loader), so it lands in <head> after any <link> we add and wins
// every tie. Prefixing each selector with the `<html data-me-enhanced>` attribute adds one attribute of specificity, so the
// enhanced rules win regardless of order, apply before any script runs, and never touch markup we don't own.
import fs from 'node:fs';
import path from 'node:path';
// Build-only tooling: postcss is not a direct dependency (css-loader brings it in), and adding one would edit package.json.
/* eslint-disable import/no-extraneous-dependencies */
import postcss from 'postcss';
/* eslint-enable import/no-extraneous-dependencies */

export const SCOPE = '[data-me-enhanced]';
export const rootDir = path.resolve(import.meta.dirname, '../..');
export const outputPath = path.join(rootDir, 'enhanced/public/css/enhanced.css');

// The designer's file ends with scaffolding for the design canvas (section 23); it is not part of the app.
const CANVAS_ONLY = /\/\* -{10} 23\. Component-sheet scaffolding/;
const SOURCES = ['enhanced/design/style.css', 'enhanced/design/adapters.css'];

export const scopeSelector = (selector) => {
  const sel = selector.trim();
  if (sel === ':root') return SCOPE;
  if (sel.startsWith(':root')) return `${SCOPE}${sel.slice(':root'.length)}`;
  if (/^html(?![\w-])/.test(sel)) return `html${SCOPE}${sel.slice('html'.length)}`;
  return `${SCOPE} ${sel}`;
};

export const scopeCss = (source) => {
  const root = postcss.parse(source);
  root.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
    rule.selectors = rule.selectors.map(scopeSelector);
  });
  return root.toString();
};

export const buildEnhancedCss = ({ root = rootDir } = {}) => {
  const parts = SOURCES.map((file) => {
    let css = fs.readFileSync(path.join(root, file), 'utf8');
    const canvasStart = css.search(CANVAS_ONLY);
    if (canvasStart !== -1) css = css.slice(0, canvasStart);
    return `/* ===== ${file} ===== */\n${scopeCss(css).trim()}\n`;
  });
  const header = '/* GENERATED by `node enhanced/tools/build-css.js` — edit enhanced/design/*.css, not this file.\n'
    + `   Every selector is scoped to ${SCOPE}; see enhanced/tools/scopeCss.js for why. */\n\n`;
  return header + parts.join('\n');
};
